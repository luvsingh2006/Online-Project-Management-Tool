package com.pmtool.db.embedded;

import java.sql.*;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

public class EmbeddedConnection implements Connection {

    private final EmbeddedDatabaseEngine engine;
    private final String url;
    private boolean autoCommit = true;
    private boolean closed = false;

    public EmbeddedConnection(EmbeddedDatabaseEngine engine, String url) {
        this.engine = engine;
        this.url = url;
    }

    public EmbeddedDatabaseEngine getEngine() { return engine; }

    @Override public Statement createStatement() throws SQLException { checkClosed(); return new EmbeddedStatement(this); }
    @Override public PreparedStatement prepareStatement(String sql) throws SQLException { checkClosed(); return new EmbeddedPreparedStatement(this, sql); }
    @Override public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException { return prepareStatement(sql); }
    @Override public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException { return prepareStatement(sql); }
    @Override public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException { return prepareStatement(sql); }

    @Override public void setAutoCommit(boolean autoCommit) throws SQLException { checkClosed(); this.autoCommit = autoCommit; }
    @Override public boolean getAutoCommit() throws SQLException { checkClosed(); return autoCommit; }
    @Override public void commit() throws SQLException { checkClosed(); engine.persist(); }
    @Override public void rollback() throws SQLException { checkClosed(); }
    @Override public void close() throws SQLException { this.closed = true; }
    @Override public boolean isClosed() throws SQLException { return closed; }

    private void checkClosed() throws SQLException {
        if (closed) throw new SQLException("Connection is closed");
    }

    @Override public DatabaseMetaData getMetaData() { return null; }
    @Override public void setReadOnly(boolean readOnly) {}
    @Override public boolean isReadOnly() { return false; }
    @Override public void setCatalog(String catalog) {}
    @Override public String getCatalog() { return "pmtool"; }
    @Override public void setTransactionIsolation(int level) {}
    @Override public int getTransactionIsolation() { return TRANSACTION_READ_COMMITTED; }
    @Override public SQLWarning getWarnings() { return null; }
    @Override public void clearWarnings() {}
    @Override public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException { return createStatement(); }
    @Override public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException { return prepareStatement(sql); }
    @Override public CallableStatement prepareCall(String sql) throws SQLException { throw new SQLException("Unsupported"); }
    @Override public String nativeSQL(String sql) { return sql; }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException { throw new SQLException("Unsupported"); }
    @Override public Map<String, Class<?>> getTypeMap() { return null; }
    @Override public void setTypeMap(Map<String, Class<?>> map) {}
    @Override public void setHoldability(int holdability) {}
    @Override public int getHoldability() { return 0; }
    @Override public Savepoint setSavepoint() throws SQLException { return null; }
    @Override public Savepoint setSavepoint(String name) throws SQLException { return null; }
    @Override public void rollback(Savepoint savepoint) throws SQLException {}
    @Override public void releaseSavepoint(Savepoint savepoint) throws SQLException {}
    @Override public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException { return createStatement(); }
    @Override public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException { return prepareStatement(sql); }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException { throw new SQLException("Unsupported"); }
    @Override public Clob createClob() { return null; }
    @Override public Blob createBlob() { return null; }
    @Override public NClob createNClob() { return null; }
    @Override public SQLXML createSQLXML() { return null; }
    @Override public boolean isValid(int timeout) { return !closed; }
    @Override public void setClientInfo(String name, String value) {}
    @Override public void setClientInfo(Properties properties) {}
    @Override public String getClientInfo(String name) { return null; }
    @Override public Properties getClientInfo() { return new Properties(); }
    @Override public Array createArrayOf(String typeName, Object[] elements) { return null; }
    @Override public Struct createStruct(String typeName, Object[] attributes) { return null; }
    @Override public void setSchema(String schema) {}
    @Override public String getSchema() { return "PUBLIC"; }
    @Override public void abort(Executor executor) { closed = true; }
    @Override public void setNetworkTimeout(Executor executor, int milliseconds) {}
    @Override public int getNetworkTimeout() { return 0; }
    @Override public <T> T unwrap(Class<T> iface) { return null; }
    @Override public boolean isWrapperFor(Class<?> iface) { return false; }
}
